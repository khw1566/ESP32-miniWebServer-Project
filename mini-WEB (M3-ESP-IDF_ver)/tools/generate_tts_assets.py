"""Regenerate embedded voice data and the OFL Korean LVGL font; no compilation.

    python tools/generate_tts_assets.py            # voice data and Korean font
    python tools/generate_tts_assets.py --voice    # voice data only
    python tools/generate_tts_assets.py --font     # Korean font only
Voice files are stored zlib-packed and inflated into PSRAM while eSpeak reads them.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tts_data/espeak-ng-data'


def voice_bytes(path):
    raw = path.read_bytes()
    # Language definitions are text; a Windows checkout adds CR which the manifest excludes.
    return raw.replace(b'\r\n', b'\n') if path.relative_to(DATA).parts[0] == 'lang' else raw


def generate_voice():
    files = sorted(p for p in DATA.rglob('*') if p.is_file())
    assert struct.unpack('<I', (DATA / 'phondata').read_bytes()[:4])[0] == 0x014801
    parts = ['/* Generated by tools/generate_tts_assets.py. eSpeak voice data: GPL-3.0-or-later.',
             ' * Each file is zlib level 9; m3_tts_data.c inflates it into PSRAM while it is open. */']
    records, manifest, packed_total = [], {}, 0
    for index, path in enumerate(files):
        raw = voice_bytes(path)
        packed = zlib.compress(raw, 9)
        packed_total += len(packed)
        parts.append(f'static const unsigned char voice_data_{index}[] = {{')
        parts += ['    ' + ','.join(f'0x{c:02x}' for c in packed[i:i + 24]) + ',' for i in range(0, len(packed), 24)]
        parts.append('};')
        name = path.relative_to(DATA).as_posix()
        records.append(f'    {{"/espeak-ng-data/{name}", voice_data_{index}, {len(raw)}, sizeof(voice_data_{index})}},')
        manifest[name] = {'size': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()}
    parts += ['static const voice_asset_t voice_assets[] = {', *records, '};', '']
    (ROOT / 'main/m3_tts_assets.inc').write_text('\n'.join(parts), encoding='utf-8', newline='\n')
    (ROOT / 'tts_data/manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
    total = sum(v['size'] for v in manifest.values())
    print(f'Embedded {total:,} voice bytes packed to {packed_total:,}.')


def generate_font():
    from PIL import Image, ImageDraw, ImageFont
    import font_pack
    font = ImageFont.truetype(str(ROOT / 'third_party/nanum-gothic/NanumGothic-Regular.ttf'), 16)
    # Glyphs are drawn from the ascender line; the baseline is 14 px down, so each 18 px box
    # extends 4 px below it (ofs_y=-4). This keeps Hangul aligned with Montserrat fallback text.
    codepoints = list(range(0x3131, 0x318F)) + list(range(0xAC00, 0xD7A4))
    bitmap = bytearray()
    for cp in codepoints:
        image = Image.new('L', (16, 18))
        ImageDraw.Draw(image).text((0, 0), chr(cp), font=font, fill=255, anchor='lt')
        pixels = [int(p >= 110) for p in image.get_flattened_data()]
        bitmap.extend(sum(pixels[i + bit] << (7 - bit) for bit in range(8)) for i in range(0, len(pixels), 8))
    parts = ['/* Generated Korean glyphs from Nanum Gothic (SIL OFL 1.1). See third_party/nanum-gothic/OFL.txt. */',
             '#include "m3_font_bitmap.h"', 'extern const lv_font_t m3_font_cjk;']
    parts += font_pack.c_lines(bitmap)
    parts += ['''static bool describe(const lv_font_t *font, lv_font_glyph_dsc_t *out, uint32_t cp, uint32_t next) {
    (void)font; (void)next;
    unsigned index;
    if (cp >= 0x3131 && cp <= 0x318e) index = cp - 0x3131;
    else if (cp >= 0xac00 && cp <= 0xd7a3) index = cp - 0xac00 + 94;
    else return false;
    out->adv_w = 16; out->box_w = 16; out->box_h = 18;
    out->ofs_x = 0; out->ofs_y = -4;
    out->format = LV_FONT_GLYPH_FORMAT_A1; out->is_placeholder = false;
    out->gid.index = index * 36;
    return true;
}''',
              'const lv_font_t m3_font_korean = {',
              '    .get_glyph_dsc=describe, .get_glyph_bitmap=m3_font_bitmap,',
              '    .line_height=20, .base_line=4, .dsc=&bitmap, .fallback=&m3_font_cjk', '};', '']
    (ROOT / 'main/m3_font_korean.c').write_text('\n'.join(parts), encoding='utf-8', newline='\n')
    print(f'{len(codepoints):,} Korean glyphs / {len(bitmap):,} bitmap bytes.')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--voice', action='store_true')
    parser.add_argument('--font', action='store_true')
    args = parser.parse_args()
    both = not args.voice and not args.font
    if args.voice or both:
        generate_voice()
    if args.font or both:
        generate_font()


if __name__ == '__main__':
    main()
