"""Validate tools/sound_packs.json and emit main/m3_sound_packs.inc. No build or network needed.

The device synthesizes every note, so a sound set costs a few hundred bytes of
Flash instead of WAV data. Previews: the m3-sound-design skill renders the same
synthesis to WAV files.  Run:  python tools/generate_sound_packs.py
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / 'tools/sound_packs.json'
OUT = ROOT / 'main/m3_sound_packs.inc'
WAVES = ['sine', 'triangle', 'square', 'bell']
SEQUENCES = {'boot': 2000, 'tap': 60, 'confirm': 800, 'error': 800, 'setup': 800}
APP_CUES = 16


def check_note(where, note):
    hz, ms, wave, gain = note
    assert hz == 0 or 200 <= hz <= 4000, f'{where}: {hz} Hz is outside the small speaker range'
    assert 10 <= ms <= 1000, f'{where}: {ms} ms'
    assert wave in WAVES, f'{where}: wave {wave}'
    assert 1 <= gain <= 100, f'{where}: gain {gain}'


def load():
    spec = json.loads(SPEC.read_text(encoding='utf-8'))
    assert spec['rate'] == 24000, 'firmware synthesizes at 24 kHz'
    packs = spec['packs']
    assert 1 <= len(packs) <= 8 and len({p['id'] for p in packs}) == len(packs)
    for pack in packs:
        for name, limit in SEQUENCES.items():
            notes = pack[name]
            assert 1 <= len(notes) <= 12, f'{pack["id"]}.{name}: 1-12 notes'
            for i, note in enumerate(notes):
                check_note(f'{pack["id"]}.{name}[{i}]', note)
            total = sum(n[1] for n in notes)
            assert total <= limit, f'{pack["id"]}.{name}: {total} ms exceeds {limit} ms'
            assert notes[0][0] and notes[-1][0], f'{pack["id"]}.{name}: starts and ends with a tone'
        app = pack['app']
        check_note(f'{pack["id"]}.app', [app['base'], app['ms'], app['wave'], app['gain']])
        top = app['base'] + app['step'] * (APP_CUES - 1)
        assert 0 <= app['step'] <= 200 and top <= 4000, f'{pack["id"]}.app reaches {top} Hz'
        assert set(pack['name']) == {'en', 'ko', 'ja'}
    return packs


def emit(packs):
    def notes(values):
        return ', '.join(f'{{{hz}, {ms}, M3_WAVE_{wave.upper()}, {gain}}}' for hz, ms, wave, gain in values)
    lines = ['/* Sound sets. Generated by tools/generate_sound_packs.py from tools/sound_packs.json. */']
    for pack in packs:
        for name in SEQUENCES:
            lines.append(f'static const m3_tone_t {pack["id"]}_{name}[] = {{{notes(pack[name])}}};')
    lines.append('static const m3_sound_pack_t sound_packs[] = {')
    for pack in packs:
        seqs = ', '.join(f'{{{pack["id"]}_{name}, {len(pack[name])}}}' for name in SEQUENCES)
        app = pack['app']
        lines.append(f'    {{{seqs}, {{{app["base"]}, {app["ms"]}, M3_WAVE_{app["wave"].upper()}, {app["gain"]}}}, {app["step"]}}}, /* {pack["id"]} */')
    lines += ['};', '_Static_assert(sizeof(sound_packs) / sizeof(sound_packs[0]) == M3_SOUND_PACK_COUNT, "sound set count");', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def main():
    packs = load()
    emit(packs)
    total = sum(len(p[n]) for p in packs for n in SEQUENCES)
    print(f'Sound sets: {len(packs)} ({", ".join(p["id"] for p in packs)}), {total} notes, about {total * 6 + len(packs) * 48} bytes of tables.')


if __name__ == '__main__':
    main()
