const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'web/index.html'),'utf8');
const output='// Generated by tools/embed_home.cjs from web/index.html.\n#include "web_pages.h"\n\nconst char FACTORY_INDEX_HTML[] =\n'+html.split(/(?<=\n)/).filter(Boolean).map(line=>'    '+JSON.stringify(line)).join('\n')+';\nconst size_t FACTORY_INDEX_HTML_LEN = sizeof(FACTORY_INDEX_HTML) - 1;\n';
fs.writeFileSync(path.join(root,'main/web_page_factory.c'),output);
console.log(`M3 factory page: ${Buffer.byteLength(html)} bytes`);
