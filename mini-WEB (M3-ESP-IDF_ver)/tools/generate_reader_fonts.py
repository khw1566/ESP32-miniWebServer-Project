"""Generate 24px, 2bpp reader faces from bundled OFL fonts. No compiler.

Includes Latin-1, Hangul compatibility jamo and all 11,172 Hangul syllables.
The UI fonts are independent. Rebuild only with: python tools/generate_reader_fonts.py
"""
from pathlib import Path
import hashlib
import json
import struct
import zlib
from PIL import ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ['nanum-gothic/NanumGothic-Regular.ttf',
         'nanum-gothic/NanumGothic-Bold.ttf',
         'nanum-myeongjo/NanumMyeongjo-Regular.ttf']
POINTS = [*range(32, 127), *range(160, 256), *range(0x3131, 0x318f), *range(0xac00, 0xd7a4)]


def supported_points(path):
    """Read the BMP cmap, so a TTF's empty .notdef never hides the fallback."""
    data = path.read_bytes()
    u16 = lambda offset: struct.unpack_from('>H', data, offset)[0]
    u32 = lambda offset: struct.unpack_from('>I', data, offset)[0]
    cmap = next(u32(i+8) for i in range(12, 12+16*u16(4), 16) if data[i:i+4] == b'cmap')
    points = set()
    for i in range(cmap+4, cmap+4+8*u16(cmap+2), 8):
        table = cmap+u32(i+4)
        if u16(table) != 4:
            continue
        count = u16(table+6)//2
        ends, starts = table+14, table+16+count*2
        deltas, ranges = starts+count*2, starts+count*4
        for segment in range(count):
            delta, distance = u16(deltas+segment*2), u16(ranges+segment*2)
            for cp in range(u16(starts+segment*2), u16(ends+segment*2)+1):
                glyph = u16(ranges+segment*2+distance+2*(cp-u16(starts+segment*2))) if distance else cp
                if glyph and (glyph+delta) & 0xffff:
                    points.add(cp)
    return points


def main():
    lines = ['/* Generated by tools/generate_reader_fonts.py. Nanum fonts: SIL OFL 1.1.',
             ' * Licenses: third_party/nanum-gothic/OFL.txt, third_party/nanum-myeongjo/OFL.txt. */']
    manifest = []
    for face, filename in enumerate(FONTS):
        path = ROOT / 'third_party' / filename
        font = ImageFont.truetype(str(path), 24)
        supported = supported_points(path)
        assert all(cp in supported for cp in POINTS if (cp < 127 or cp >= 0x3131) and cp != 0x3164)
        blob, glyphs = bytearray(), []
        for cp in POINTS:
            if cp not in supported:
                glyphs.append((len(blob), 0, 0, 0, 0, 0))
                continue
            mask, (ox, oy) = font.getmask2(chr(cp), mode='L', anchor='ls')
            w, h = mask.size
            assert w <= 32 and h <= 32
            pixels = [(p * 3 + 127) // 255 for p in bytes(mask)]
            pixels.extend([0] * (-len(pixels) % 4))
            data = bytes(sum(pixels[i+j] << (6-2*j) for j in range(4)) for i in range(0, len(pixels), 4))
            glyphs.append((len(blob), round(font.getlength(chr(cp))), w, h, ox, -oy-h))
            blob.extend(data)
        packed = zlib.compress(blob, 9)
        lines += [f'static const uint8_t reader_packed_{face}[] = {{']
        lines += ['    '+','.join(f'0x{v:02x}' for v in packed[i:i+24])+',' for i in range(0, len(packed), 24)]
        lines += ['};', f'static m3_font_blob_t reader_blob_{face} = {{reader_packed_{face}, sizeof(reader_packed_{face}), {len(blob)}, NULL}};',
                  f'static const reader_glyph_t reader_glyphs_{face}[] = {{']
        lines += ['    {'+','.join(map(str, g))+'},' for g in glyphs]
        lines += ['};']
        ascent = max(g[3]+g[5] for g in glyphs)
        descent = max(-g[5] for g in glyphs)
        assert ascent <= 26 and descent <= 8, (filename, ascent, descent)
        manifest.append(dict(file=filename, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                             glyphs=len(glyphs), raw_bytes=len(blob), packed_bytes=len(packed),
                             missing=[f'{cp:04X}' for cp in POINTS if cp not in supported],
                             ascent=ascent, descent=descent))
    lines += ['static const reader_face_t reader_faces[] = {']
    lines += [f'    {{&reader_blob_{i}, reader_glyphs_{i}}},' for i in range(len(FONTS))]
    lines += ['};', '']
    (ROOT / 'main/m3_reader_fonts.inc').write_text('\n'.join(lines), encoding='utf-8')
    (ROOT / 'third_party/reader-fonts.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
