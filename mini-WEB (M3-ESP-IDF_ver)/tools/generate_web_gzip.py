"""Losslessly compress built-in web pages. Standard library only; no compiler."""
from pathlib import Path
import gzip
import json
import re

ROOT = Path(__file__).resolve().parents[1]
STRING = re.compile(r'"(?:\\.|[^"\\])*"')


def page(name, filename):
    source = (ROOT / 'main' / filename).read_text(encoding='utf-8')
    source = source.split('const char ' + name + '[] =', 1)[1]
    if name == 'HTML_ADMIN_DASHBOARD':
        definitions = (ROOT / 'main/web_sd_admin_ui.inc').read_text(encoding='utf-8')
        for macro in ('SD_ADMIN_HTML', 'SD_ADMIN_SCRIPT'):
            value = definitions.split('#define ' + macro, 1)[1].split('#define', 1)[0]
            source = source.replace(macro, re.sub(r'\\\r?\n', '', value))
    # These generated C assets use JSON-compatible string literals. Fail closed
    # if a new C expression/macro appears, rather than silently omitting content.
    remainder = STRING.sub('', source).strip()
    if remainder != ';':
        raise ValueError(f'Unexpected expression in {name}: {remainder[:80]}')
    return ''.join(json.loads(m[0]) for m in STRING.finditer(source)).encode('utf-8')


def generate():
    lines = ['/* Generated by tools/generate_web_gzip.py. Do not edit. */', '#include "web_pages.h"']
    raw_total = packed_total = 0
    for name, filename in [('HTML_ADMIN_DASHBOARD', 'web_page_admin.c'), ('HTML_AI_STUDIO', 'web_page_ai.c')]:
        raw = page(name, filename)
        packed = gzip.compress(raw, compresslevel=9, mtime=0)
        assert gzip.decompress(packed) == raw
        lines.append(f'const unsigned char {name}_GZIP[] = {{')
        lines.extend('    ' + ','.join(f'0x{b:02x}' for b in packed[i:i+24]) + ',' for i in range(0, len(packed), 24))
        lines.extend(['};', f'const size_t {name}_GZIP_LEN = sizeof({name}_GZIP);'])
        raw_total += len(raw) + 1
        packed_total += len(packed)
    text = '\n'.join(lines) + '\n'
    destination = ROOT / 'main/web_pages_gzip.c'
    if not destination.exists() or destination.read_text(encoding='utf-8') != text:
        destination.write_text(text, encoding='utf-8', newline='\n')
    print(f'Web assets: {raw_total} -> {packed_total} bytes; data reduction {raw_total-packed_total} bytes (before linking/alignment)')


if __name__ == '__main__':
    generate()
