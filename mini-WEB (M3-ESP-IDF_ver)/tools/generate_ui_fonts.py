"""Generate the anti-aliased touch UI fonts from Nanum Gothic (SIL OFL 1.1).

m3_font_title: 22 px semibold Hangul for TITLE(...) strings in main/m3_i18n.c,
               with the shared CJK 22px fallback and Montserrat 20 for ASCII.
m3_font_clock: 84 px digits for the home clock.
Run after changing Korean title text:  python tools/generate_ui_fonts.py
"""
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / 'third_party/nanum-gothic/NanumGothic-Regular.ttf'


def title_characters():
    header = (ROOT / 'main/include/m3_i18n.h').read_text(encoding='utf-8')
    source = (ROOT / 'main/m3_i18n.c').read_text(encoding='utf-8')
    titles = set(re.findall(r'TITLE\((\w+)\)', header))
    chars = {'가'}  # TTS app icon
    for name, korean in re.findall(r'\[T_(\w+)\] = \{"(?:[^"\\]|\\.)*", "((?:[^"\\]|\\.)*)"\}', source):
        if name in titles:
            chars.update(c for c in korean if 0xAC00 <= ord(c) <= 0xD7A3)
    return sorted(chars)


def render(chars, size, scale, embolden):
    font = ImageFont.truetype(str(TTF), size * scale)
    ascent, descent = font.getmetrics()
    pad = size * scale
    glyphs = []
    for ch in chars:
        canvas = Image.new('L', (pad * 4, pad * 4))
        baseline = pad * 2
        ImageDraw.Draw(canvas).text((pad, baseline), ch, font=font, fill=255, anchor='ls',
                                    stroke_width=embolden, stroke_fill=255)
        small = canvas.resize((canvas.width // scale, canvas.height // scale), Image.LANCZOS)
        box = small.getbbox()
        advance = (font.getlength(ch) + embolden * 2) / scale
        if not box:
            glyphs.append((ch, advance, 0, 0, 0, 0, b''))
            continue
        left, top, right, bottom = box
        crop = small.crop(box)
        pixels = [p >> 4 for p in crop.get_flattened_data()]
        if len(pixels) % 2:
            pixels.append(0)
        data = bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))
        glyphs.append((ch, advance, right - left, bottom - top, left - pad // scale,
                       baseline // scale - bottom, data))
    return glyphs, round(ascent / scale), round(descent / scale)


def emit(name, glyphs, ascent, descent, fallback, comment):
    out = [f'/* {comment} Generated by tools/generate_ui_fonts.py from Nanum Gothic (SIL OFL 1.1). */',
           '#include "lvgl.h"']
    if fallback == '&m3_font_large':
        out.append('extern const lv_font_t m3_font_large;')
    out.append('static const uint8_t bitmap[] = {')
    blob = bytearray()
    descs = ['    {0},']
    for ch, advance, w, h, ox, oy, data in glyphs:
        descs.append(f'    {{.bitmap_index={len(blob)}, .adv_w={round(advance * 16)}, .box_w={w}, .box_h={h}, '
                     f'.ofs_x={ox}, .ofs_y={oy}}}, /* U+{ord(ch):04X} */')
        blob.extend(data)
    out += ['    ' + ','.join(f'0x{c:02x}' for c in blob[i:i + 24]) + ',' for i in range(0, len(blob), 24)] or ['    0']
    out += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', *descs, '};']
    codes = [ord(g[0]) for g in glyphs]
    first = codes[0]
    out.append('static const uint16_t unicode_list[] = {' + ','.join(f'0x{c - first:x}' for c in codes) + '};')
    out += ['static const lv_font_fmt_txt_cmap_t maps[] = {',
            f'    {{.range_start=0x{first:x}, .range_length={codes[-1] - first + 1}, .glyph_id_start=1, '
            f'.unicode_list=unicode_list, .list_length={len(codes)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}',
            '};', 'static const lv_font_fmt_txt_dsc_t description = {',
            '    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=maps, .cmap_num=1, .bpp=4', '};',
            f'const lv_font_t {name} = {{',
            '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
            f'    .line_height={ascent + descent}, .base_line={descent}, .dsc=&description, .fallback={fallback}',
            '};', '']
    (ROOT / f'main/{name}.c').write_text('\n'.join(out), encoding='utf-8', newline='\n')
    return len(blob)


chars = title_characters()
glyphs, ascent, descent = render(chars, 22, 4, 3)
# The ink box includes antialiasing and the semibold stroke, unlike TTF metrics.
ascent = max(g[3] + g[5] for g in glyphs) + 1
descent = max(0, -min(g[5] for g in glyphs)) + 1
title_bytes = emit('m3_font_title', glyphs, ascent, descent, '&m3_font_large',
                   'Semibold 22 px Hangul for UI titles.')
glyphs, ascent, descent = render(list('-0123456789:'), 84, 4, 0)
# Digits have no descenders: fit the line box to the inked height so the clock sits tightly.
ascent = max(g[5] + g[3] for g in glyphs) + 2
descent = max(0, -min(g[5] for g in glyphs)) + 2
clock_bytes = emit('m3_font_clock', glyphs, ascent, descent, 'NULL', '84 px clock digits.')
print(f'title: {len(chars)} Hangul glyphs / {title_bytes:,} bitmap bytes; clock: {clock_bytes:,} bitmap bytes')
