/* Units and separators inside formatted radio/microphone status lines. */
static const text_pair_t tokens[] = {
    {" / net ", " / 수신 "}, {" / gaps ", " / 끊김 "}, {" / 8 seconds / level ", " / 8초 / 음량 "},
};
#include "m3_i18n_ja.inc"

static m3_lang_t language = M3_LANG_KO;

void m3_i18n_load(void) {
    nvs_handle_t nvs; uint8_t saved = 0;
    if (nvs_open("m3_ui", NVS_READONLY, &nvs) != ESP_OK) return;
    if (nvs_get_u8(nvs, "lang", &saved) == ESP_OK && saved < M3_LANG_COUNT) language = (m3_lang_t)saved;
    nvs_close(nvs);
}
m3_lang_t m3_i18n_language(void) { return language; }
bool m3_i18n_set_language(m3_lang_t next) {
    if ((unsigned)next >= M3_LANG_COUNT) return false;
    language = next;
    nvs_handle_t nvs;
    if (nvs_open("m3_ui", NVS_READWRITE, &nvs) == ESP_OK) {
        if (nvs_set_u8(nvs, "lang", (uint8_t)next) == ESP_OK) nvs_commit(nvs);
        nvs_close(nvs);
    }
    return true; /* The change still applies for this session if NVS is unavailable. */
}
const char *tr(m3_text_t id) {
    if ((unsigned)id >= T_COUNT || !texts[id].en) return "";
    if (language == M3_LANG_JA && japanese_texts[id]) return japanese_texts[id];
    return language == M3_LANG_KO && texts[id].ko ? texts[id].ko : texts[id].en;
}
const char *m3_i18n_status(const char *english, char *buffer, size_t size) {
    if (!english || language == M3_LANG_EN || !size) return english ? english : "";
    const text_pair_t *best = NULL; size_t best_length = 0;
    for (size_t i = 0; i < sizeof(statuses) / sizeof(statuses[0]); ++i) {
        size_t length = strlen(statuses[i].en);
        if (length > best_length && !strncmp(english, statuses[i].en, length)) { best = &statuses[i]; best_length = length; }
    }
    if (!best) return english;
    const char *prefix = language == M3_LANG_JA ? japanese_statuses[best - statuses] : best->ko;
    size_t used = m3_utf8_copy(buffer, size, prefix);
    if (used < strlen(prefix)) return buffer;
    for (const char *rest = english + best_length; *rest && used + 1 < size;) {
        const text_pair_t *token = NULL;
        for (size_t i = 0; i < sizeof(tokens) / sizeof(tokens[0]); ++i)
            if (!strncmp(rest, tokens[i].en, strlen(tokens[i].en))) { token = &tokens[i]; break; }
        if (token) {
            const char *value = language == M3_LANG_JA ? japanese_statuses[sizeof(statuses) / sizeof(statuses[0]) + (token - tokens)] : token->ko;
            size_t copied = m3_utf8_copy(buffer + used, size - used, value); used += copied;
            if (copied < strlen(value)) break;
            rest += strlen(token->en);
        } else {
            unsigned char lead = (unsigned char)*rest;
            size_t bytes = lead >= 0xf0 ? 4 : lead >= 0xe0 ? 3 : lead >= 0xc2 ? 2 : 1;
            if (bytes >= size - used || strnlen(rest, bytes) != bytes) break;
            memcpy(buffer + used, rest, bytes); used += bytes; rest += bytes; buffer[used] = 0;
        }
    }
    return buffer;
}
