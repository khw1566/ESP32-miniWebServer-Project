// Regenerate the C asset without compiling firmware.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..','main');
const js=fs.readFileSync(path.join(root,'ai_studio.js'),'utf8').replace(/<\/script/gi,'<\\/script');
const html=fs.readFileSync(path.join(root,'ai_studio.html'),'utf8').replace('/* AI_STUDIO_SCRIPT */',()=>js);
fs.writeFileSync(path.join(root,'web_page_ai.c'),'// Generated by tools/embed_ai_studio.cjs from ai_studio.html and ai_studio.js.\n#include "web_pages.h"\n\nconst char HTML_AI_STUDIO[] =\n'+html.split(/(?<=\n)/).map(line=>'    '+JSON.stringify(line)).join('\n')+';\n');
