// Keep the standalone P4 page and its first-boot firmware copy identical.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
// Hosted authoring uses its local checkout; a Git clone uses the tracked example.
const hostedInput = path.join(root, 'sites/p4-webserver/dist/index.html');
const exampleInput = path.join(root, 'web_examples/13_p4_webserver/index.html');
const input = fs.existsSync(hostedInput) ? hostedInput : exampleInput;
const sourceName = path.relative(root, input).split(path.sep).join('/');
const html = fs.readFileSync(input, 'utf8').replace(/\r\n/g, '\n');
const example = path.join(root, 'web_examples/13_p4_webserver');
fs.mkdirSync(example, { recursive: true });
fs.writeFileSync(path.join(example, 'index.html'), html);
const output = path.join(root, 'mini-WEB (P4-ESP-IDF_ver)/main/web_page_factory.c');
const lines = html.split(/(?<=\n)/).map(line => '    ' + JSON.stringify(line)).join('\n');
fs.writeFileSync(output, `// Generated by tools/embed_p4_home.cjs from ${sourceName}.\n` +
  '#include "web_pages.h"\n\nconst char FACTORY_INDEX_HTML[] =\n' + lines + ';\n' +
  'const size_t FACTORY_INDEX_HTML_LEN = sizeof(FACTORY_INDEX_HTML) - 1;\n');
console.log(`P4 home: ${Buffer.byteLength(html)} bytes; example and firmware synchronized.`);
