// Embed the product home page (web_examples/00_product_home/index.html) into
// every firmware as main/web_page_factory.c. The board copies it to
// /spiffs/index.html on first boot (web_factory_seed in web_server.c).
// Run after editing the page:  node tools/embed_factory_page.cjs
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const pageDirectory = path.join(root, 'web_examples', '00_product_home');
const pagePath = path.join(pageDirectory, fs.existsSync(path.join(pageDirectory, 'index.html')) ? 'index.html' : 'index1.html');
const sourceName = path.relative(root, pagePath).split(path.sep).join('/');
const page = fs.readFileSync(pagePath, 'utf8').replace(/\r\n/g, '\n');
const boards = ['M1', 'S3-N16R8-SD', 'S3', 'C3'];
const body = page.split(/(?<=\n)/).map(line => '    ' + JSON.stringify(line)).join('\n');
const source = `// Generated by tools/embed_factory_page.cjs from ${sourceName}.\n` +
  '#include "web_pages.h"\n\n' +
  'const char FACTORY_INDEX_HTML[] =\n' + body + ';\n' +
  'const size_t FACTORY_INDEX_HTML_LEN = sizeof(FACTORY_INDEX_HTML) - 1;\n';
for (const board of boards) {
  const file = path.join(root, `mini-WEB (${board}-ESP-IDF_ver)`, 'main', 'web_page_factory.c');
  fs.writeFileSync(file, source);
  console.log(`${board}: ${Buffer.byteLength(page)} bytes -> ${path.relative(root, file)}`);
}
