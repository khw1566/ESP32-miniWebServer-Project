"""Sync standalone network setup sources to all five firmware projects (no build)."""
from pathlib import Path
import json
root = Path(__file__).resolve().parent.parent
common = root / 'tools/firmware_common'
for project in sorted(root.glob('mini-WEB*')):
    main = project / 'main'
    if not main.is_dir():
        continue
    for name in ['network_settings.inc', 'web_network_setup.inc']:
        (main/name).write_bytes((common/name).read_bytes())
    (main/'include/network_settings.h').write_bytes((common/'network_settings.h').read_bytes())
    html = (common/'wifi_setup.html').read_text(encoding='utf-8')
    embedded = '/* Generated by tools/sync_network_setup.py */\nstatic const char HTML_WIFI_SETUP[] =\n'
    embedded += '\n'.join(json.dumps(line, ensure_ascii=False) for line in html.splitlines(keepends=True)) + ';\n'
    (main/'web_wifi_setup_html.inc').write_text(embedded, encoding='utf-8')
    print(project.name)
