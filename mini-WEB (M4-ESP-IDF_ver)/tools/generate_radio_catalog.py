"""Generate the board catalog from the relay's public station allowlist; no compiler."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root.parent / 'tube-relay/radio_stations.json').read_text(encoding='utf-8'))
assert len({s['id'] for s in data}) == len(data)
lines = ['/* Generated by tools/generate_radio_catalog.py. Edit tube-relay/radio_stations.json. */',
         'static const struct { const char *name, *url, *id; bool aac, relay; unsigned region; } radio_stations[] = {']
for s in data:
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    lines.append('    {' + ', '.join([quote(s['name']), quote(s.get('url', '')), quote(s['id']),
                 str(s.get('aac', False)).lower(), str(bool(s.get('kbs'))).lower(), str(s['region'])]) + '},')
lines += ['};', '_Static_assert(sizeof(radio_stations) / sizeof(radio_stations[0]) <= 24, "station buttons");', '']
(root / 'main/m4_radio_stations.inc').write_text('\n'.join(lines), encoding='utf-8')
print(f'Radio catalog: {len(data)} stations.')
