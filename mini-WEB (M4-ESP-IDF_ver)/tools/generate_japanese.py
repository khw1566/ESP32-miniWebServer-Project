"""Validate and emit the Japanese UI/status tables. No build or network needed."""
from pathlib import Path
import ast
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = (ROOT / 'main/m4_i18n.c').read_text(encoding='utf-8')
    data = json.loads((ROOT / 'translations/ja.json').read_text(encoding='utf-8'))
    entries = {}
    for name, body in re.findall(r'^    \[T_(\w+)\] = \{(.*?)\},$', source, re.S | re.M):
        en = ''
        for token in re.findall(r'"(?:[^"\\]|\\.)*"|,', body):
            if token == ',':
                break
            en += ast.literal_eval(token)
        entries[name] = en
    section = source[source.index('static const text_pair_t statuses[]'):source.index('static m4_lang_t language')]
    pairs = re.findall(r'\{"((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)"\}', section)
    messages = [ast.literal_eval('"' + en + '"') for en, ko in pairs]
    assert set(data['texts']) == set(entries), f'UI translation key mismatch: {set(entries) ^ set(data["texts"])}'
    assert set(data['statuses']) == set(messages), f'Status translation key mismatch: {set(messages) ^ set(data["statuses"])}'
    for name, en in entries.items():
        ja = data['texts'][name]
        assert name == 'NONE' or ja, name
        assert re.findall(r'%[-0-9.*]*l?[a-z%]', en) == re.findall(r'%[-0-9.*]*l?[a-z%]', ja), name
    emit = lambda text: json.dumps(text, ensure_ascii=False)
    lines = ['/* Japanese UI. Generated by tools/generate_japanese.py from translations/ja.json. */',
             'static const char *const japanese_texts[T_COUNT] = {']
    lines += [f'    [T_{name}] = {emit(data["texts"][name])},' for name in entries]
    lines += ['};', 'static const char *const japanese_statuses[] = {']
    # Statuses and tokens share the same source region, in that order.
    lines += [f'    {emit(data["statuses"][name])},' for name in messages]
    lines += ['};', '_Static_assert(sizeof(japanese_statuses) / sizeof(japanese_statuses[0]) ==',
              '    sizeof(statuses) / sizeof(statuses[0]) + sizeof(tokens) / sizeof(tokens[0]), "Japanese status alignment");', '']
    (ROOT / 'main/m4_i18n_ja.inc').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Japanese: {len(entries)} UI strings, {len(messages)} service/status tokens.')


if __name__ == '__main__':
    main()
