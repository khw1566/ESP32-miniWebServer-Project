// One-time setup: creates the shared token, config.json and the board header
// main/include/m3_tube_private.h (git-ignored) so the firmware knows URL + token.
// Usage: node setup.mjs [https://tube.audreaming.com] [--rotate]
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const configPath = path.join(ROOT, 'config.json');
const url = (process.argv.slice(2).find(a => a.startsWith('http')) || 'https://tube.audreaming.com').replace(/\/+$/, '');
const rotate = process.argv.includes('--rotate');
const config = fs.existsSync(configPath) ? JSON.parse(fs.readFileSync(configPath, 'utf8')) : {};
if (!config.token || rotate) config.token = crypto.randomBytes(24).toString('base64url');
config.publicUrl = url;
fs.writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n');

const header = path.join(ROOT, '..', 'mini-WEB (M3-ESP-IDF_ver)', 'main', 'include', 'm3_tube_private.h');
fs.writeFileSync(header, [
  '/* Generated by tube-relay/setup.mjs. Git-ignored: contains the relay token. */',
  '#pragma once',
  `#define M3_TUBE_URL "${url}"`,
  `#define M3_TUBE_TOKEN "${config.token}"`, '',
].join('\n'));
console.log(`config.json  : ${configPath}`);
console.log(`board header : ${header}`);
console.log(`public URL   : ${url}`);
console.log(rotate ? 'Token rotated: rebuild and flash the firmware.' : 'Token ready. Rebuild the firmware after the first setup.');
